export interface IpcCommandContract {
  name: string;
  module: string;
  args: string[];
  result: string;
}

const COMMAND_ATTRIBUTE = "#[tauri::command]";

function matchingParen(source: string, openIndex: number): number {
  let depth = 0;
  for (let index = openIndex; index < source.length; index += 1) {
    const char = source[index];
    if (char === "(") depth += 1;
    if (char === ")") {
      depth -= 1;
      if (depth === 0) return index;
    }
  }
  return -1;
}

function splitParams(source: string): string[] {
  const params: string[] = [];
  let current = "";
  let depth = 0;
  for (const char of source) {
    if (char === "<" || char === "(" || char === "[") depth += 1;
    if (char === ">" || char === ")" || char === "]") depth -= 1;
    if (char === "," && depth === 0) {
      if (current.trim()) params.push(current.trim());
      current = "";
      continue;
    }
    current += char;
  }
  if (current.trim()) params.push(current.trim());
  return params;
}

function returnType(source: string, start: number): string {
  const arrow = source.indexOf("->", start);
  if (arrow === -1) return "()";
  let depth = 0;
  for (let index = arrow + 2; index < source.length; index += 1) {
    const char = source[index];
    if (char === "<" || char === "(" || char === "[") depth += 1;
    if (char === ">" || char === ")" || char === "]") depth -= 1;
    if (char === "{" && depth === 0) {
      return source.slice(arrow + 2, index).replace(/\s+/g, " ").trim();
    }
  }
  return "";
}

export function parseIpcCommandContracts(
  source: string,
  module: string
): IpcCommandContract[] {
  const contracts: IpcCommandContract[] = [];
  let cursor = 0;
  while (true) {
    const attribute = source.indexOf(COMMAND_ATTRIBUTE, cursor);
    if (attribute === -1) break;
    const fn = source.indexOf("fn ", attribute);
    if (fn === -1) break;
    const nameStart = fn + 3;
    const open = source.indexOf("(", nameStart);
    const name = source.slice(nameStart, open).trim();
    const close = matchingParen(source, open);
    if (open === -1 || close === -1) break;
    const args = splitParams(source.slice(open + 1, close)).map((param) =>
      param.slice(0, param.indexOf(":")).trim()
    );
    contracts.push({
      name,
      module,
      args,
      result: returnType(source, close),
    });
    cursor = close;
  }
  return contracts;
}

export function formatIpcContract(contracts: IpcCommandContract[]): string {
  const unique = new Map<string, IpcCommandContract>();
  for (const contract of contracts) {
    if (!unique.has(contract.name)) unique.set(contract.name, contract);
  }
  const modules = new Map<string, IpcCommandContract[]>();
  for (const contract of unique.values()) {
    const group = modules.get(contract.module) ?? [];
    group.push(contract);
    modules.set(contract.module, group);
  }
  const lines = [
    "# IPC command contract",
    "",
    "Generated from `#[tauri::command]` signatures by `bun run check:ipc`.",
    "Do not edit this file by hand.",
    "",
  ];
  for (const [module, entries] of [...modules.entries()].sort(([left], [right]) =>
    left.localeCompare(right)
  )) {
    lines.push(`## ${module}`, "", "| Command | Arguments | Result |", "| --- | --- | --- |");
    for (const entry of [...entries].sort((left, right) => left.name.localeCompare(right.name))) {
      lines.push(
        `| \`${entry.name}\` | ${entry.args.map((arg) => `\`${arg}\``).join(", ") || "-"} | \`${entry.result}\` |`
      );
    }
    lines.push("");
  }
  return lines.join("\n");
}
